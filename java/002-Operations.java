/* Create a Java program which will display the result 
 * of the 5 basic arithmetic operations between 
 * 2 hardcoded integer numbers
 */

public class Operations {
    public static void main(String[] args) {
        System.out.println(123+456);
        System.out.println(123-456);
        System.out.println(123*456);
        System.out.println(123/456);
        System.out.println(123.0/456);
        System.out.println(123%100);
    }
}
